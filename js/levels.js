// DAILY: 날짜 시드로 만드는 좌우 대칭 스테이지
export function dailyStage(rng, i) {
  const rows = [E];
  const n = 6 + Math.floor(rng() * 4);
  for (let r = 0; r < n; r++) {
    const style = rng();
    const col = String(1 + Math.floor(rng() * 7));
    let half = '';
    for (let c = 0; c < 7; c++) {
      let ch;
      if (style < 0.35) ch = col;
      else if (style < 0.55) ch = c % 2 === 0 ? col : '.';
      else if (style < 0.7) ch = rng() < 0.7 ? col : '.';
      else if (style < 0.8) ch = c % 2 ? 'H' : col;
      else if (style < 0.88) ch = c % 3 === 0 ? 'S' : (rng() < 0.6 ? col : '.');
      else if (style < 0.94) ch = c % 2 ? 'G' : col;
      else ch = c % 3 === 1 ? 'B' : col;
      if (ch === col && rng() < 0.04) ch = 'T';
      else if (ch === col && i >= 2 && rng() < 0.05) ch = 'R';
      half += ch;
    }
    rows.push(half + half.slice(0, 6).split('').reverse().join(''));
  }
  if (i >= 1 && rng() < 0.7) rows.push('M............');
  return rows;
}

// ENDLESS: 위에서 내려오는 줄 하나
export function endlessRow(rng, level, n) {
  // 강철·재생 벽돌은 넣지 않는다: 부술 수 없는 벽돌이 한계선에 닿으면 피할 수 없는 패배가 된다
  const col = String(1 + (n % 7));
  let s = '';
  for (let c = 0; c < 13; c++) {
    let ch = col;
    if (rng() < 0.1) ch = '.';
    else {
      const r = rng();
      const hard = Math.min(0.2, 0.05 + level * 0.012);
      if (r < hard) ch = level >= 6 && rng() < 0.3 ? 'I' : 'H';
      else if (r < hard + 0.04) ch = 'B';
      else if (r < hard + 0.11 && level >= 2) ch = 'G';
      else if (r < hard + 0.13) ch = 'T';
    }
    s += ch;
  }
  return s;
}
